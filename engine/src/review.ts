// ReviewForm -> PlannedReview. Pure: everything GitHub-shaped about a review
// (anchors, suggestion syntax, the downgrade rule, thread replies, the body
// cap) is decided here so reconcile only has to post what it is handed.

import { buildDiffMap, type DiffMap } from "./diffmap.js";
import type {
  EngineConfig,
  Finding,
  InlineComment,
  ModelRef,
  PlannedReview,
  PullRequestFacts,
  ReviewForm,
  ReviewPayload,
  ReviewThread,
  ThreadAction,
} from "./types.js";

/** GitHub rejects bodies over 65,536 characters; stay clear of it. */
export const BODY_MAX_CHARS = 65_000;

const TRUNCATED_NOTE = "[goobreview: truncated to fit GitHub's size limit.]";

export interface PlanContext {
  config: EngineConfig;
  model: ModelRef;
  elapsedMs: number;
  engineVersion: string;
}

interface Placement {
  path: string;
  line: number;
  startLine?: number;
  introduced: boolean;
}

export function planReview(
  form: ReviewForm,
  facts: PullRequestFacts,
  ctx: PlanContext,
): PlannedReview {
  const diff = buildDiffMap(facts.files);
  const maxLines = ctx.config.budgets.suggestionMaxLines;
  const notes: string[] = [];
  const comments: InlineComment[] = [];
  const unplaced: Finding[] = [];
  let blockingOnAdded = false;

  for (const finding of form.findings) {
    const at = place(finding, diff);
    if (!at) {
      unplaced.push(finding);
      notes.push(`unplaced: ${finding.title}${locationOf(finding) ? ` (${locationOf(finding)})` : ""}`);
      continue;
    }
    if (finding.blocking && at.introduced) blockingOnAdded = true;
    const parts = [`### ${oneLine(finding.title)}`, finding.body.trim()];
    if (finding.suggestion !== undefined) {
      const { block, demoted } = suggestionBlock(finding.suggestion, maxLines);
      parts.push(block);
      if (demoted) notes.push(`demoted suggestion: ${finding.title}`);
    }
    const comment: InlineComment = { path: at.path, line: at.line, side: "RIGHT", body: cap(join(parts), BODY_MAX_CHARS) };
    if (at.startLine !== undefined) comment.startLine = at.startLine;
    comments.push(comment);
  }

  // #113: a blocking verdict must rest on something this PR introduced.
  // Findings on context or pre-existing lines, or ones we could not anchor,
  // are advice, not grounds to block the merge.
  let event = form.verdict;
  let downgradeNote: string | undefined;
  if (event === "REQUEST_CHANGES" && !blockingOnAdded) {
    event = "COMMENT";
    downgradeNote =
      "[goobreview: posted as COMMENT because no blocking finding is anchored on a line this PR added, so the review was not treated as blocking.]";
    notes.push("downgraded REQUEST_CHANGES to COMMENT: no blocking finding anchored on an added line");
  }

  const sections: string[] = [form.summary.trim()];
  if (downgradeNote) sections.push(downgradeNote);
  for (const finding of unplaced) sections.push(bodySection(finding));
  if (form.notCovered.length > 0) {
    sections.push(`Not covered by this review: ${form.notCovered.map((p) => `\`${oneLine(p)}\``).join(", ")}.`);
  }
  const footer = `---\n${footerNote(ctx)}`;
  const main = join(sections);
  const body = cap(main, BODY_MAX_CHARS - footer.length - 2) + "\n\n" + footer;
  if (main.length + footer.length + 2 > BODY_MAX_CHARS) notes.push("review body truncated to fit GitHub's limit");

  const payload: ReviewPayload = { commitId: facts.headSha, event, body, comments };
  return { payload, threadActions: threadActions(form, facts, ctx.config.autoResolveBotThreads), notes };
}

/** Body for a REQUEST_CHANGES posted without calling the model because required CI failed. */
export function ciFailureReview(facts: PullRequestFacts, failing: string[]): ReviewPayload {
  const byName = new Map(facts.checkRuns.map((c) => [c.name, c]));
  const summary =
    failing.length === 0
      ? "No check summary available."
      : failing.map((name) => `${name}: ${byName.get(name)?.conclusion ?? byName.get(name)?.status ?? "failing"}`).join("\n");
  const body = [
    "CI is failing on this commit. Fix the failing job(s) and push a new commit - I will re-review on the new head SHA.",
    fenced(summary, ""),
    "---\n*Auto-generated by goobreview. CI was non-green at review time, so no model call was made.*",
  ].join("\n\n");
  return { commitId: facts.headSha, event: "REQUEST_CHANGES", body: cap(body, BODY_MAX_CHARS), comments: [] };
}

// ---------------------------------------------------------------------------

function place(finding: Finding, diff: DiffMap): Placement | undefined {
  if (finding.path === undefined || finding.line === undefined) return undefined;
  const file = diff.get(finding.path);
  if (!file || !file.right.has(finding.line)) return undefined;
  const start = finding.startLine;
  if (start === undefined || start >= finding.line) {
    return { path: finding.path, line: finding.line, introduced: file.added.has(finding.line) };
  }
  // A range is valid only inside one hunk, where RIGHT lines are contiguous.
  // Across hunks the anchor would silently cover lines GitHub never showed,
  // and a suggestion would replace the wrong span, so keep it in the body.
  if (!file.right.has(start) || file.hunkOf.get(start) !== file.hunkOf.get(finding.line)) return undefined;
  let introduced = false;
  for (let l = start; l <= finding.line; l++) if (file.added.has(l)) introduced = true;
  return { path: finding.path, line: finding.line, startLine: start, introduced };
}

function suggestionBlock(suggestion: string, maxLines: number): { block: string; demoted: boolean } {
  const text = suggestion.replace(/\r\n/g, "\n").replace(/\n$/, "");
  const count = text === "" ? 0 : text.split("\n").length;
  if (count <= maxLines) return { block: fenced(text, "suggestion"), demoted: false };
  return {
    block: `${fenced(text, "")}\n[goobreview: suggestion of ${count} lines exceeds the ${maxLines}-line cap; shown as a snippet, not an applicable suggestion.]`,
    demoted: true,
  };
}

function bodySection(finding: Finding): string {
  const parts = [`### ${oneLine(finding.title)}`];
  const loc = locationOf(finding);
  if (loc) parts.push(`Location: \`${loc}\``);
  parts.push(finding.body.trim());
  // Suggestions only apply from an inline comment; in the body they are just code.
  if (finding.suggestion !== undefined) parts.push(`Suggested replacement:\n\n${fenced(finding.suggestion.replace(/\n$/, ""), "")}`);
  return join(parts);
}

function threadActions(
  form: Pick<ReviewForm, "resolvedThreads" | "unresolvedThreads">,
  facts: PullRequestFacts,
  autoResolve: boolean,
): ThreadAction[] {
  const open = new Map<string, ReviewThread>();
  for (const t of facts.botThreads) if (!t.isResolved && !open.has(t.handle)) open.set(t.handle, t);
  const sha = facts.headSha;
  const actions: ThreadAction[] = [];
  const seen = new Set<string>();
  // Still-open wins when the model lists a handle both ways: leaving a real
  // problem open is the cheaper mistake.
  for (const u of form.unresolvedThreads) {
    const thread = open.get(u.handle);
    if (!thread || seen.has(u.handle)) continue;
    seen.add(u.handle);
    actions.push({ thread, kind: "reply", body: `Still open at ${sha}: ${u.explanation.trim()}` });
  }
  for (const r of form.resolvedThreads) {
    const thread = open.get(r.handle);
    if (!thread || seen.has(r.handle)) continue;
    seen.add(r.handle);
    const evidence = r.evidence.trim();
    if (autoResolve && thread.viewerCanResolve) {
      actions.push({ thread, kind: "resolve", body: `Confirmed fixed at ${sha} — resolving this thread.${evidence ? `\n\n${evidence}` : ""}` });
    } else {
      actions.push({ thread, kind: "reply", body: `Looks fixed at ${sha}.${evidence ? ` ${evidence}` : ""}` });
    }
  }
  return actions;
}

export function formatDuration(ms: number): string {
  const s = Math.max(0, Math.floor(ms / 1000));
  return s >= 60 ? `${Math.floor(s / 60)}m${String(s % 60).padStart(2, "0")}s` : `${s}s`;
}

function footerNote(ctx: PlanContext): string {
  const v = ctx.engineVersion;
  const engine = /^\d+\.\d+\.\d+$/.test(v)
    ? `[goobreview ${v}](https://github.com/asavs/goobreview/releases/tag/v${v})`
    : `goobreview ${v || "unknown"}`;
  return `*${ctx.model.provider}/${ctx.model.id} took ${formatDuration(ctx.elapsedMs)} via ${engine}.*`;
}

function locationOf(f: Finding): string | undefined {
  if (f.path === undefined) return undefined;
  if (f.line === undefined) return f.path;
  return f.startLine !== undefined && f.startLine < f.line ? `${f.path}:${f.startLine}-${f.line}` : `${f.path}:${f.line}`;
}

/** Fence `text` with a backtick run longer than any inside it. */
function fenced(text: string, info: string): string {
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const fence = "`".repeat(Math.max(3, longest + 1));
  return `${fence}${info}\n${text}${text === "" ? "" : "\n"}${fence}`;
}

const oneLine = (s: string): string => s.replace(/\s+/g, " ").trim();
const join = (parts: string[]): string => parts.filter((p) => p.trim() !== "").join("\n\n");

/** Truncate at a line boundary under `max` chars, closing an open code fence. */
export function cap(text: string, max: number): string {
  if (text.length <= max) return text;
  const room = Math.max(0, max - TRUNCATED_NOTE.length - 16);
  let cut = text.slice(0, room);
  const nl = cut.lastIndexOf("\n");
  if (nl > room / 2) cut = cut.slice(0, nl);
  // Don't leave half a surrogate pair at the end.
  if (/[\uD800-\uDBFF]$/.test(cut)) cut = cut.slice(0, -1);
  let open: string | undefined;
  for (const m of cut.matchAll(/^\s*(`{3,})/gm)) {
    const run = m[1] ?? "";
    if (open === undefined) open = run;
    else if (run.length >= open.length) open = undefined;
  }
  if (open !== undefined) cut += `\n${open}`;
  return `${cut}\n\n${TRUNCATED_NOTE}`;
}
